/**
 * @file  DelayTuning.h
 * @brief 延迟算法的**全部可调常数**（对标实测值的单一落点）
 *
 * 与 ReverbTuning.h 同一套约定与同一个理由：这些数字全部来自对参考插件
 * （Tone King Imperial MKII 的 Delay 段）的黑箱测量，测量脚本在
 * tools/measure/ref_delay_*.py，逐条结论在 docs/REFERENCE.md §14。
 *
 * 命名约定：
 *   kMeas*  —— 直接实测量（改动必须有新测量支撑）
 *   kFit*   —— 由测量拟合出的模型参数
 *   kArch*  —— 结构性选择（受实测约束但非唯一解）
 *
 * ------------------------------------------------------------
 * 拓扑（实测确定，不是猜的）
 * ------------------------------------------------------------
 * 每个判据的原始数据见 §14，这里只记结论与它依赖的那一条判据：
 *
 *   in ──┬────────────────────────────────── dry ──────┬── out
 *        │                                             │
 *        └─→ [延迟线 D + LFO 调制写指针] ─┬─→ ×wet ─→ [饱和] ─┘
 *                    ↑                    │
 *                    └── ×fb ← [LP] ← [HP] ┘
 *
 * * **LP / HP 在环内**：判据是逐次回声的谱**累积**变化。HIGH PASS fc=353 Hz
 *   在 100 Hz 上给出 −20.68 / −40.66 / −59.34 / −85.34 dB —— 严格的 ×k
 *   等差，只有「每绕一圈滤一次」能产生。环外（post）会让所有回声的谱**形状
 *   相同**，只差幅度。这是定性判据，不需要拟合。
 * * **饱和在湿声总线、环外**：判据是高幅度下逐次回声的幅度比**与 k 无关**，
 *   且从 amp=1e-3 到 amp=1.0 这组比值不变（0.599/0.662/0.682/0.701）。
 *   环内饱和会让比值随 k 递增（后面的回声幅度小、压得轻）。
 *   进一步地，drywet=0 时干路增益恒为 1.000000（amp=1.0 也是）⇒
 *   饱和**不在输入端**，只在湿路。
 * * **Dry/Wet 不是交叉淡入淡出**，是「干路恒定 + 湿路线性增益」：
 *   干增益在 norm 0.00…0.75 上恒为 1.000000，而湿声峰值线性上升
 *   （0 / 1.3193e-04 / 2.6386e-04 / 3.9579e-04）。norm=1.00 时干路才归零。
 * * **Stereo 模式零交叉馈送**（R@Dl = 0.000e+00）；**Mono 模式**把两路输入
 *   求和喂一条延迟线，两个输出取同一条。
 */

