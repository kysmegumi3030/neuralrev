// ============================================================
// 环内反馈系数（实测，与显示值不同）
// ------------------------------------------------------------
// §6.1 的前车之鉴（显示的 fc 不是 −3 dB 点）要求这一条必须用信号读。
// 读法与三重交叉验证见 tools/measure/ref_delay_fb.py 与 ref_delay_fb2.py：
//
// 为什么不能用「逐次回声的能量比」直接读：LP/HP 在环内 ⇒ 每圈的能量损失
// = 反馈系数 × 滤波器损耗，而损耗依赖当时的谱形状（谱越窄，后续每圈损失
// 越小）。所以能量比随回声序号**递增**（0.671/0.718/0.739/0.751），
// 一个纯标量反馈不可能这样。
//
// 正确读法：**窄带 Hann 猝发**（2048 样点正弦），LP 开到 16 kHz、HP 压到
// 20 Hz，用最小二乘 sin/cos 投影读单一频点的幅度比。此时：
//   * 比值对回声序号 k **恒定**（std 0.0012–0.0045）⇒ 滤波器损耗已排除；
//   * 比值**与延迟时长无关**（0.78518 / 0.78414 / 0.78367 / 0.78171，
//     对应 D = 4800 / 15223 / 37892 / 52800）⇒ 确认是标量。
//
// 剩下的偏倚是频率依赖：即使 LP 名义 16 kHz，环内在 4 kHz 上仍有可观损耗
//（单回声谱在 4 kHz 已 −5.50 dB）。所以取**损耗极小处**的读数。
// ============================================================

/// 归一反馈 = 1.0（显示 0.50）时的**环内实际系数**：**0.80**，
/// 即显示值的 **1.6 倍**。显示串第三次不描述 DSP（另两次是
/// delay_note_ms 的路径开关与 delay_sync 的极性反转）。
///
/// 定值依据（三个频点、两条独立路径）：
///   * 在环内损耗的**极小平台**（100/200/350 Hz，L 平到 5e-5）读 norm=1.0
///     得 0.79636 / 0.79591 / 0.79640，三点相对 0.80 一致偏低 0.45%；
///   * 那 0.45% 正是平台上的**残余**损耗（−0.039 dB），与同一条 L(f) 曲线
///     在 1 kHz 的 −0.137 dB、2 kHz 的 −0.524 dB 平滑衔接 ⇒ 外推 L→1 给出
///     整数 0.80，而不是 0.796 这个带损耗的读数。
inline constexpr double kMeasFeedbackMax = 0.80;

/// 反馈在**归一域**的量化步长 = 1/50。
///
/// 环内用的不是连续归一值，而是**显示串上那个两位小数**：显示范围
/// 0.00–0.50、步长 0.01 ⇒ 归一域 51 格（0…50）。
///
/// 判据是阶梯的三条硬特征，全部在 350 Hz（L 极大处）读，故 L(f) 与 D 完全相消：
///   1. **平台**：同格内读数相同到 **0.0002%**（0.295/0.300/0.305/0.309 四点
///      全部给出 0.238916，而连续律要求它们相差 4.8%）；
///   2. **跳变**：跨格时按格号之比跳（15→16 跳 1.066668，实测/预测 1.0667）；
///   3. **正比于格号**：coeff/格号 = 0.0159277 / 0.01592775 / 0.01592776 /
///      0.01592778（格 15…18），六位一致。
/// 过原点拟合：量化模型最差偏差 **0.0001%**，连续模型 3.69% ⇒ 差 43060 倍。
///
/// 这与混响段 DRY/WET 的 kMeasDryWetQuant = 0.01 是同一个现象 ——
/// 这家插件把用户可见的两位小数直接当 DSP 系数。
inline constexpr double kMeasFeedbackQuantSteps = 50.0;

/// coeff = kMeasFeedbackMax · round(50·norm)/50
inline double feedbackFromNorm(double norm) noexcept
{
    const double n = std::clamp(norm, 0.0, 1.0);
    const double q = std::floor(n * kMeasFeedbackQuantSteps + 0.5)
                   / kMeasFeedbackQuantSteps;
    return kMeasFeedbackMax * q;
}

// ============================================================
// 延迟线 LFO（实测，机制已定）
// ------------------------------------------------------------
// 五项独立测量，全部在 docs/REFERENCE.md §14.5：
//   * **速率 1.70186 Hz**：四个不同的采样节奏（12/16/19.2/24 Hz 冲激列）
//     给出的值散布只有 3e-5 Hz ⇒ 不是欠采样别名。
//   * **正弦波**：正弦拟合残差 0.370%，三角波假设 21.302%。
//   * **确定性、锚定在渲染起点的绝对时间**：重复渲染 Δ=0；渲染长度 +4 s
//     Δ=0；激励提前**整周期** ⇒ 深度重合到 0.0181 样点；提前**半周期**
//     ⇒ 反相（23.85 样点）。
//   * **L/R 共用一个 LFO**：相关 +0.999998，滞后 0。
// ============================================================

inline constexpr double kMeasLfoRateHz = 1.70186;

/// LFO 调制的是**写指针**，不是读指针。判据是深度随延迟时长的律：
///
///   depth(D) = 2·A·|sin(π·D/T)|,   T = 采样率 / kMeasLfoRateHz
///
/// 若调制加在写指针（或等价地，延迟量取「写入时刻的 LFO」与「读出时刻的
/// LFO」之差），读指针在 D 个样点后取值，看到的净调制 ∝
/// sin(ωt) − sin(ω(t−D/SR))，幅度正是 2A|sin(ωD/2SR)|。
///
/// 这条律是**零自由度的形状检验**（A 只定纵轴单位）：18 个延迟时长
/// （100…1100 ms）上最差**绝对**偏差 0.0226 样点，幅度 >0.5 处最差相对
/// 偏差 1.92%。
///
/// 决定性证据是 norm=0.65 处的**真零点**：深度掉到 0.0122 样点（邻档小两个
/// 数量级），且 D/T = 1.00027 —— 延迟长度恰好等于一个 LFO 周期，两路同相
/// 相消。穿越零点时初相跳 178.2°（+16.37° → −161.82°）⇒ 是相消而非衰减。
///
/// 副产品：深度的**非单调**（3.32↗6.50↘0.01↗6.25↘2.57）不再需要任何查表，
/// 它是机制的推论。
inline constexpr double kMeasLfoAmpSamples = 3.27550;

/// LFO 周期（样点）。
inline double lfoPeriodSamples(double sr) noexcept
{
    return sr / kMeasLfoRateHz;
}

/// 读出端看到的净调制深度（样点，峰值），D 为基准延迟样点数。
/// 这是上面那条律的直接实现 —— 候选侧**不**照抄这个值，而是复制机制
///（调制写指针），深度自然涌现。此函数仅供对拍脚本核对用。
inline double lfoNetDepthSamples(double delaySamples, double sr) noexcept
{
    const double T = lfoPeriodSamples(sr);
    return 2.0 * kMeasLfoAmpSamples * std::fabs(std::sin(M_PI * delaySamples / T));
}

