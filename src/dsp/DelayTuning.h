inline double tempoBpmFromNorm(double norm) noexcept
{
    const double n = std::clamp(norm, 0.0, 1.0);
    return kMeasTempoMinBpm + (kMeasTempoMaxBpm - kMeasTempoMinBpm) * n;
}

/// Sync 路径：档位索引 + tempo → 延迟时长（ms），含 100–1100 ms 的夹取。
inline double syncNoteMs(int noteIndex, double bpm) noexcept
{
    const int i = std::clamp(noteIndex, 0, kMeasSyncNoteCount - 1);
    const double beat = 60000.0 / std::max(1.0, bpm);
    const double ms = kMeasSyncNoteFractions[static_cast<size_t>(i)] * beat * 4.0;
    return std::clamp(ms, kMeasTimeMinMs, kMeasTimeMaxMs);
}

// ============================================================
// Dry/Wet 混合律（实测：不是交叉淡入淡出，但也不是硬门）
// ------------------------------------------------------------
// ⚠️ 这一段被改过一次。旧结论「干路在 norm<1 恒 1、norm=1 突然归零」
// 是采样太稀造成的（只取了 0.00/0.25/0.50/0.75/1.00 五点，正好跳过膝点）。
// 加密到 0.82/0.85/0.88/0.90/0.94/0.97 之后，真相是**两段线性**：
//
//   干： dw ≤ 0.82  →  0.997996（平）
//        dw > 0.82  →  0.997996 · (1 − dw)/0.18
//        实测 0.85/0.88/0.90/0.94/0.97 给出 0.8317/0.6653/0.5544/
//        0.3327/0.1663，而 (1−dw)/0.18 = 0.8333/0.6667/0.5556/0.3333/
//        0.1667 —— 六位吻合。
//   湿： dw ≤ 0.82  →  1.943552 · dw
//        dw > 0.82  →  1.593713（钳位）
//
// **两条律共用同一个膝点 0.82**：湿声在此停止增长，干声在此开始下降。
// 一个拐点同时出现在两条独立读数里 ⇒ 是设计，不是测量噪声。
// 净效果：0…0.82 上湿声渐入而干声不动（总能量上升），0.82…1.0 上
// 干声退出而湿声不动（真正的交叉只发生在最后 18%）。
// ============================================================

inline double dryGainFromNorm(double norm) noexcept
{
    const double n = std::clamp(norm, 0.0, 1.0);
    if (n <= kMeasMixKnee)
        return kMeasDryGain;
    return kMeasDryGain * (1.0 - n) / (1.0 - kMeasMixKnee);
}

inline double wetGainFromNorm(double norm) noexcept
{
    const double n = std::clamp(norm, 0.0, 1.0);
    return kMeasWetGainSlope * std::min(n, kMeasMixKnee);
}

