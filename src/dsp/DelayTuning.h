// 用户 LP / HP：二阶 Butterworth，**显示 fc 就是真 −3 dB 点**
// ------------------------------------------------------------
// 这一条与混响段**相反**（§6.1：混响的显示 fc 不是 −3 dB 点），
// 所以必须单独验，不能类推。判据是「在名义 fc 上量比值」：
//
//   LP=0.0（名义 1000 Hz）  @1 kHz  −3.00 dB
//   LP=0.4（名义 3046 Hz）  @3 kHz  −2.87 dB
//   LP=0.7（名义 7908 Hz）  @8 kHz  −3.07 dB
//
// 三档都落在 −3 dB，⇒ 显示串诚实。阶数由斜率定：LP=0.0 档在 2fc / 3fc 处
// 实测 −12.36 / −18.98 dB，二阶 Butterworth 理论 −12.30 / −19.08 —— 差 0.1 dB
// （一阶理论 −7.0 / −10.0，差十几 dB，排除）。
//
// HP 同样：fc=800 Hz 档在 200 / 350 / 700 Hz 实测 −24.18 / −14.60 / −4.44，
// 二阶 Butterworth 理论 −24.1 / −14.5 / −4.32。
//
// 测法见 tools/measure/ref_delay_loop_filter.py：先把已定死的反馈标量 0.80
// 除掉，得到每圈损耗 L(f)，再拿不同档位的 L 相除 —— 固定部分被消掉，
// 剩下的纯粹是用户滤波器。
// ============================================================
inline constexpr int kMeasUserFilterOrder = 2;
inline constexpr double kMeasUserFilterQ = 0.7071;   // Butterworth 二阶

// ============================================================
// 环内**固定**滤波器（用户 LP 之外的那一级）
// ------------------------------------------------------------
// 为什么知道它存在：LP 开到 16 kHz 时，每圈损耗在 8 kHz 上仍有 −7.83 dB。
// 一个 16 kHz 的二阶低通在 8 kHz 只吃 −0.26 dB ⇒ 差的 7.6 dB 来自别处。
//
// 剥掉 16 kHz 二阶之后的固定部分（dB）：
//   1k     2k     3k     4k     5k     6k     8k
//  -0.176 -0.563 -1.175 -1.983 -2.977 -4.194 -7.828
//
// **它不是极点滤波器**：1…12 阶 Butterworth 全扫过，最好只到 2.20 dB
// （M=3, fc=5540 Hz），且残差呈系统性 S 形。dB 损耗在 1–8 kHz 上近似 ∝ f²，
// 那是**内插/平滑核**的特征 —— 混响那轮踩过同一个坑（§10.2.2：线性插值的
// 损耗被误当成 damping）。
//
// 但验收口径（逐 bin ≤3 dB）只要求**复制 L(f)**，不要求给机制起名字。
// 所以落点取「两级二阶低通级联」的拟合值：
//   可信带（100 Hz…8 kHz）内最差偏差 **0.046 dB**，比最好的单极点族好 48 倍。
//
// 可信带的界定不是随手划的：逐圈比值用第 2…6 个回声，单圈损耗 X dB ⇒
// 第 6 个回声低 5X dB。激励 1e-3（−60 dBFS）下，单圈超过约 14 dB 时
// 末尾回声已进 float 本底、比值被**抬高** —— 实测 10 kHz / 12 kHz 两点
// 正是如此（LP=0.0 列在 3 kHz 之后甚至从 −20 dB 反弹到 −1.5 dB，
// 损耗不可能自己变小）。故 10 kHz 以上排除在拟合之外，只作外推。
//
// 残差是一条**平的 +0.04 dB 偏置**，不是形状误差 —— 即每圈还差 0.45%，
// 正是 kMeasFeedbackMax 那里 0.796 与 0.80 的差。两处读数因此自洽。
// ============================================================
// ============================================================
// ⚠️ 以下 kFitLoopFixedLp* 已**废弃**，保留只为记录那条走过的弯路。
// 现在环内固定损耗用 kMeasLoopFirTaps（下面那个 24 抽头 FIR），理由见其注释。
// 简述：两级二阶最好只到 2.97 dB、三级反而 4.17 dB，因为真实响应是
// 「中频缓降 + 12–16 kHz 一堵 40 dB/oct 的墙」，极点族做不出这个组合。
// ============================================================
// 落点是**闭环校正后**的拟合值，不是直接拟合参考原始表的那一组。
// 区别与理由：参考侧的 L(f) 是用 band_amp 逐圈估计器读出来的，
// 那个估计器本身有偏（窄带猝发有有限带宽，而环内斜坡陡 ⇒ 窗内低侧频率
// 损耗小，单频投影读到的是加权平均，系统性**少读**损耗，8 kHz 上 0.29 dB）。
// 偏倚在两侧都存在，所以不该去抵消它；但拟合目标必须是
// 「候选的解析响应该落在哪」= ref_L − bias − 平项，而不是 ref_L 本身。
// 用校正后的目标重扫，最差偏差 0.0460 → **0.0183 dB**。
// 全过程见 tools/fit/fit_delay_loop_filter.py 的「闭环校正」段。
inline constexpr double kFitLoopFixedLpAHz = 6500.0;
inline constexpr double kFitLoopFixedLpAQ = 0.500;
inline constexpr double kFitLoopFixedLpBHz = 8700.0;
inline constexpr double kFitLoopFixedLpBQ = 0.950;

// ============================================================
// 环内固定滤波器：**直接测出来的 24 抽头 FIR**
// ------------------------------------------------------------
// 这一条取代了原先「两级二阶级联 + 平项」的拟合落点。为什么换：
//
// 1. **有一个不需要拟合的测法。** feedback=0 时的单回声就是环内滤波器的
//    冲激响应**恰好一次**通过 —— 打一个冲激进去，把 echo1 那一段截出来
//    就是它。原先那条路（逐圈幅度比 ÷ 反馈标量）绕了远路：估计器有偏
//    （窄带猝发 × 陡斜坡，8 kHz 上少读 0.29 dB）、受动态范围限制
//    （单圈 >14 dB 就进本底，10 k/12 k 只能外推），还得反过来做闭环校正。
//    直接读没有这些问题，而且一路能读到 20 kHz（−86 dB）。
// 2. **极点族拟合不动这个形状。** 直接读出的响应是「中频缓降 + 12–16 kHz
//    一堵 40 dB/oct 的墙 + 之上转平」。二级二阶最好 2.97 dB，三级 4.17 dB
//    （更差 —— 阶数不是瓶颈，形状才是）。这形状像内部超采样的抗镜像滤波器。
// 3. **群延迟也必须对上，而不只是幅度。** 参考的 echo1 峰位比理论 D 晚
//    22 样点，逐圈再累积（+16/+2/+15/+3）。幅度拟合不管相位，级联二阶只有
//    约 4 样点，于是对拍出来 lag=−27。FIR 直接带着实测的群延迟。
//
// 提取步骤（全部可复现）：
//   * 冲激 1e-2 进参考，LP=1.0、HP=0.0、fb=0，取 y[at+D+15 : +4096]；
//     那 +15 是响应真正起头的位置（之前的样点 <1e-6 峰值）。
//   * 长尾是**用户 HP**（20 Hz 二阶）造成的，不是抗镜像核的一部分 ——
//     判据：把 HP 抬到 ~280 Hz，第 20/40 抽头从 −0.0051/−0.0055 变成
//     −0.0537/−0.0242，随 HP 走。故用 lfilter(a, b) 把那一级反卷积掉。
//   * 剩下的核在第 24 抽头之后均值只有 1.5e−05 ⇒ 24 抽头足够。
//
//   * ⚠️ **还要把 16 kHz 用户 LP 也反卷积掉。** 提取是在 delay_lowpass=1.0
//     上做的，那一档的用户 LP 是 16 kHz 二阶 Butterworth，**并没有旁通** ——
//     所以它整个含在读出的核里。若照原样填进环内，运行时再串一级 16 kHz LP
//     就是重复计入。判据（直接读数，不是推理）：候选的 echo1 相对参考在
//     10 k/12 k 上低 9.45/14.96 dB，而这两点正是「多过一次 16 kHz LP」的量；
//     同时已实测排除内插器（15 阶 Lagrange 在 12 kHz 最坏只 0.009 dB）。
//     反卷积后核变长一点（第 28 抽头后均值 1.5e−05）⇒ 取 28 抽头。
//
// 核对（对 LP=1.0 实测的 L(f)，用 **FIR + 一级 16 kHz 用户 LP** 合成）：
//   100 Hz…16 kHz 最差 **0.049 dB**；20 kHz 处 2.35 dB
//   （那里参考已在 −86 dB，远在 −80 dB 谱门之下，不参与判据）。
//   抽头数的取舍：24 抽头同口径 3.06 dB、32 抽头 2.36 dB ⇒ 28 是拐点。
// 另一个自洽性检查：抽头之和 = 1.595993，而湿声平台实测 1.593713 ——
// 两次独立测量差 0.14%。（DC 增益就该等于湿声平台，因为湿声抽头在滤波之后。）
//
// ⚠️ 平项 kFitLoopFlatGain **不再单独乘**：FIR 的 DC 增益里已经含了它
