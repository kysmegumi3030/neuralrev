// ------------------------------------------------------------
// 分数延迟插值的阶数（ModulatedDelay 的读指针）
// ------------------------------------------------------------
// 插值器在环内**每圈施加一次**，是一个与用户参数无关的固定低通。
// 这个「与设定无关」正是它的指纹：实测 18–20 kHz 的亏空在 HIGH CUT
// 三档（−3.47 / −3.39 / −3.38 dB）与 DECAY 两档（−3.36 / −3.73）上
// 几乎不动 —— 若病根在 HIGH CUT 拐点律或环内 damping，读数必随之变化。
// allpass 扩散级是幅度平坦的，也不可能造成倾斜。排除法之后只剩这一项。
//
// 为什么 3 阶不够（它是上一轮从线性插值改过来的，已经好了 5.6 倍）：
//   顶端带实测 T60（口径 fit_damping_t60.band_t60，与参考同尾长）
//       8 kHz    ref 2.241  cand 2.148   −4.2%
//       13.5 kHz ref 1.782  cand 1.585  −11.1%
//       18 kHz   ref 1.687  cand 1.048  −37.9%
//   换算到每圈（平均线长 2626 样点 ⇒ 18.3 圈/s）：18 kHz 每圈**超额**
//   衰减 1.185 dB，而 3 阶 Lagrange 在 t 均布下 18 kHz 正好损耗 2.806 dB。
//   同一位置提到 9 阶只剩 1.179 dB ⇒ 差额 1.63 dB/圈，与需要消除的量同阶。
//
// 为什么不能靠放松 damping 或调 kFitT60BudgetScale 去补：
//   damping 是**一阶**低通（渐近 −6 dB/oct），插值损耗是 **sinc 型**，
//   在 Nyquist 附近急陡。相对 1 kHz 的额外倾斜：
//       8 kHz −0.58 / 12 kHz −1.50 / 16 kHz −3.07 / 19 kHz −4.81 dB per 圈
//   两者形状不同，单极点无论怎么取 fc 都表达不出这个形状；上一轮
//   fit_damping_t60.py 把 fc 推到超过 Nyquist（等于关掉 damping）仍差
//   −13.3%，就是这个道理（那一轮的教训 5）。**必须改插值器本身。**
//   kFitT60BudgetScale 是宽带标量，同倍移动所有带，更碰不到倾斜。
//
// 稳定性：Lagrange 插值器在任意阶、t 扫遍 0…1 时峰值 |H| 恒为 1.000000
// （实测 0…Nyquist 上取 2000 点、t 取 51 点），故提高阶数不会让反馈环
// 出现 |H|>1 的增益尖峰。这是可以放心加阶的前提。
//
// 取 15 阶（16 点）：节点跨 −7…+8，需要的缓冲余量由 setSize 的 headroom
// 参数保证（见 WetCore::prepare 传入 ceil(depth)+kArchFracNodeSpan）。
//
// 为什么从 9 提到 15（2026-08-05）：
//   9 阶时顶端仍有可测的插值损耗。把损耗按「damping 解析预测」与「其它」
//   分解后（tools/fit/diag_loop_loss.py 的口径，锚定 1 kHz、单位 dB/s）：
//       4 kHz +0.51   8 kHz +0.51   13.5 kHz +1.54   18 kHz **+11.30**
//   ——「其它」项只在顶端八度爆发，这是 sinc 型插值的指纹；一阶低通
//   不可能这么局部（它在 dB 域对 log f 平滑单调）。
//   决定性检验：把 kFitLfoDepthSamples 置 0 ⇒ d = base_ 为整数 ⇒ t = 0 ⇒
//   Lagrange 系数退化成 [0,…,1,…,0]，插值损耗**数学上恒为 0**（不是变小）。
//   此时 18 kHz 的「其它」项 +11.30 → **+0.49 dB/s**，其余带变化 ≤1.1 ⇒
//   顶端亏空的剩余部分**全部**来自插值，且提阶是对症的。
//
//   为什么不是继续调 damping fc：fit_damping_shape.py 的实测扫描给出
//   一个无解格局 —— fc=17000 时 4k/8k 几乎归零（+0.11/+0.10）但 18 kHz
//   到 −18.78；最优折中 fc=22500 处 13.5 kHz +5.80 与 18 kHz −5.14
//   **符号相反**。单参数单调族无法让两个同向缺口同时归零（教训 5）。
//   另外 diag_loop_loss.py 的第 1 节证明参考侧的损耗形状本身就是**一阶**的
//   （N=1 残差 0.1175 dB/圈，N≥2 单调变差），所以不能靠串联多级低通去凑。
//
// 阶数的边际收益（t 均布下 18 kHz 每圈损耗，diag_loop_loss.py 第 3 节）：
//       9 阶 1.131 → 11 阶 0.886 → 13 阶 0.703 → 15 阶 0.563 → 19 阶 0.368
//   折算成 dB/s 并减去实测需消除量后，15 阶是残余首次落进 ±2 dB/s 的阶数。
//   再往上（19/23 阶）会**过冲**成反向误差，且每样点的系数计算是 O(N²)。
//
// 稳定性：Lagrange 插值器在任意阶、t 扫遍 0…1 时峰值 |H| 恒为 1.000000
// （实测 0…Nyquist 上取 1500 点、t 取 101 点，3…23 阶逐阶复核），
// 故提高阶数不会让反馈环出现 |H|>1 的增益尖峰。这是可以放心加阶的前提。
inline constexpr int kArchFracInterpOrder = 15;

/// 插值节点向未来/过去各需的最大样点数，供延迟线申请余量。
inline constexpr int kArchFracNodeSpan = kArchFracInterpOrder / 2 + 2;

