/// 反馈环内固定 damping 低通的 −3 dB 点。
/// 依据：高频超额衰减的绝对值（dB/s）与 DECAY 档无关（跨档离散 ≤3 dB/s），
/// 且在 ~1.6 kHz 以下平坦、之上单调加深（2 kHz −1.0、4 kHz −3.5、
/// 8 kHz −10.0、10 kHz −13.5 dB/s）。
///
/// 落点 18400 Hz 与 kFitT60BudgetScale 由 tools/fit/fit_damping_t60.py
/// **联立**扫出（目标 = 逐带 T60 相对误差的 min–max，55.9% → 9.4%）。
/// 两者必须一起动：scale 的物理含义就是补偿环内损耗，放松 damping 会让
/// 原来的 scale 补过头（详见该常数注释）。
///
/// 这个常数被**错标过两次**，两次都是目标函数选错，记下来免得再犯：
///
///   1. 早先拟合到 800 Hz 是**被 HIGH CUT 的拐点错误带偏的** —— 当时用
///      显示值 10 kHz 当拐点（真实 12.1 kHz），高频本来就偏低，damping 便被
///      拟合成过度衰减来「补偿」。修正拐点律后重扫回到 3600 Hz。
///
///   2. 3600 Hz 也是错的，而且错得更隐蔽：它由 fit_network.py --stage damping
///      用**平滑谱**目标扫出（78.9 → 76.8），而平滑谱是整段 IR 的**时间积分**
///      量，对衰减率几乎不敏感 —— 「早期偏亮 + 尾巴过暗」与「全程正确」能积分
///      出很相近的频谱。结果高频尾巴衰减快了约 2 倍（8 kHz 的 T60 −55.5%），
///      频谱口径却显示过关，一直到人耳验收才抓出来。
///      **教训：标定衰减率的常数，目标函数必须是时间分辨量（逐带 T60），
///      不能用任何形式的积分频谱。** 详见 docs/REFERENCE.md §7.5。
inline constexpr double kFitDampingHz = 20000.0;

