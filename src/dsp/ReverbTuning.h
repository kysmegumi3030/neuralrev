// ------------------------------------------------------------
// 低频倾斜补偿（低架）—— 工具 tools/fit/fit_tilt.py
// ------------------------------------------------------------
// 修的是什么：本网络的低频比参考**整体偏热**。逐带「候选−参考」的均值
//     20–40 Hz +5.81 / 40–80 +2.51 / 80–300 +2.91 / 300–2k −1.21 dB
// 低频三带同号为正、300 Hz 以上转负 ⇒ 这是一条**整体倾斜**，
// 不是单个频段的孤立偏差，所以用一个低架就能吃掉大部分。
//
// 与 §10.2 那句结论的关系（那句话我写过头了，此处更正）：文档说
// 「调增益/滤波器/damping 都无用」—— 对「能否达到 3 dB」成立，对
// 「能否显著改善」不成立。20–40 Hz 的误差分解是均值 +5.81、去均值 max
// 8.67 dB；把均值项压平，该带 max 在数学上就从 14.48 落到约 8.7 dB。
// 剩下的 8.67 dB 是**模式错位**，确实只能靠动线长/加路数，低架碰不到它。
//
// 为什么这不算「偷改对标口径」：LOW/HIGH CUT 的拐点律（kFitLowCut* /
// kFitHighCut*）是从参考自身的滤波器扫频拟合的，与本网络的低频余量无关；
// 这个低架是**候选侧的实现补偿**，串在湿声总线上，不改那两条律。
//
// 为什么放在湿声总线、而不是环内：环内滤波会同时改变衰减率（T60 已按
// §7 的律标定好），会把 §12 刚对齐的 ±1.9% 破坏掉。总线上是纯线性后置，
// 只改频响、不改衰减。
//
// ### 现在的落点是 dB = 0，即**这一级低架已停用**。原因见下，很重要。
//
// 它曾经的落点是 −4.25 dB（全档全带 max 17.37 → 13.53），并且当时的分析
// （「20–40 与 40–80 需要的补偿方向相反、收益已榨干」）在**那个前提下**是对的。
// 前提是：本网络低频确实整体偏热 +5.81 / +2.51 / +2.91 dB。
//
// 那个前提**已经不成立**。修掉 ModulatedDelay 的线性插值损耗并重标 damping 之后
//（docs/REFERENCE.md §7.5/§7.6），逐带能量比变成一条几乎平的 +3 dB 宽带过量，
// 低频那条「倾斜」大部分本来就是**插值损耗的镜像** —— 高频在环内每圈被吃掉
// −0.8 dB，相对之下低频看起来就是偏热的。真正的病在高频，不在低频。
//
// 所以 fit_trim_tilt.py 联立扫 (kWetTrim, 本常数) 时，解自己走到了
// dB = 0：宽带过量交给 kWetTrim 的 −3.5 dB 一刀切掉，低架不再需要，
// 而它的低频衰减此时**纯粹是负担**（会把 20–40 从 −1.14 继续往下压）。
//
// 教训（与 §7.5 同源，值得单独记一条）：**用一个补偿器去修另一处实现缺陷造成的
// 假象，会在真缺陷被修掉之后变成新的偏差。** 低架当时确实把 max 从 17.37 压到
// 13.53，数字是真的、分析也是自洽的 —— 但它修的是症状。判据是它的落点在
// 上游缺陷修好后自己归零了；如果它修的是真实的网络倾斜，落点不会动。
//
// 常数**保留不删**（fc / Q 仍是标定过的值）：如果将来动了线长/路数，
// 低频倾斜可能重新出现，届时只需重扫 dB 一维即可，不必重新推导 fc。
// 关于 fc=235 Hz 为什么明显高于 20–80 Hz 这两个目标带：低架在拐点以下才是全量
// 衰减，要让 40 Hz 拿到接近满深度，拐点必须放到几百 Hz。
inline constexpr double kFitTiltShelfHz = 235.0000;
inline constexpr double kFitTiltShelfDb = 0.0000;
inline constexpr double kFitTiltShelfQ = 0.7071;

// 以下这段是**低架还启用（−4.25 dB）时**做的否证实验，前提已随上面那段作废，
// 但结论里有一条与前提无关、仍然成立，所以保留：
// **两个 2 阶低架无法分开 20–40 与 40–80**（纯滤波器几何，见末尾「为什么必然失败」）。
// 那一条对将来任何「再加一级低频补偿」的想法都还有效，不要重走。
//
// 试过并**否证**的方案：再串一级「次低档」低架（拐点落在 20–40 与 40–80 之间），
// 想把 20–40 Hz 剩下的均值也吃掉。已实现、已拟合、已删除，结论记在这里，
// 免得后来者再走一遍 —— 这条路看起来非常合理。
//
// 动机是对的：上面那级定稿后，两带的均值**方向相反**——
//     20–40 Hz +1.76（还偏热）   40–80 Hz −2.43（已经过冲）
// 一级低架的平坦区同时盖住这两带，所以它无法再往下压：继续加深度只是把
// 40–80 越推越负，min–max 目标立刻反弹（见上方「已经榨干」那段）。
//
// 但次低档也不行，**实测**：--stage sub 的 25 个网格点
// （fc 30/38/45/55/65 Hz × dB −1…−6）**无一例合格**，全部让 40–80 更糟。
// 最好的一个（fc=65 dB=−3）把 20–40 拉低约 3 dB，代价是 40–80 涨约 2.5 dB
// —— 而 40–80 当时已是最差带，所以在 min–max 口径下这是净亏。
// 最终落点退回 dB=0（即不启用），目标的变动量落在数值噪声里。
//
// 为什么必然失败：两带的几何中心只差**一个八度**（28 Hz vs 57 Hz），
// 而 2 阶低架从平坦区过渡到全量需要一个八度以上。想在 40 Hz 给足衰减、
// 同时在 57 Hz 给 0 dB，所需过渡陡度远超 2 阶 —— 拐点放低了 20–40 吃不到，
// 放高了 40–80 立刻被带下去，中间没有可行窗口。
// 提高 Q 也不行：低架的 Q 只在拐点附近造出凸起/凹陷，不会让过渡带变陡，
// 只会把 40–80 的退化换成一个局部峰。
//
// 结论：20–40 与 40–80 这两带**不可能靠总线上的线性滤波分开处理**。
// 它和那 10.58 dB 的去均值项一样，只能靠改网络（线长/路数）。
//（当时的结论是「所以只保留一级低架」；现在连那一级也归零了，见上。
//  但这条几何论证与低架是否启用无关，将来若低频倾斜重现，仍然只能用**一级**。）

// ------------------------------------------------------------
// 两个 CUT 滤波器的**真实拐点律**（关键修正，工具 tools/measure/ref_cut_law.py）
// ------------------------------------------------------------
// 显示串上的 fc **不是** −3 dB 点。两条独立证据：
//   * 比值法（ref_lowcut_shape.py）：lowcut=0 档在 20→40 Hz 的斜率实测
//     +8.4 dB/oct，与「旁通」模型（+12.0）相符、与「真 50 Hz 高通」
//     模型（+1.4）不符 ⇒ 最低档几乎不滤波；
//   * REFERENCE §6：显示 fc=212 Hz 档 @fc 只有 −0.05 dB，
//     真 2 极点在自己拐点处必然 −3…−6 dB。
// 用全曲线最小二乘（7 个档位联立，有效区 |R| ∈ [1,35] dB，避开顶部 0 dB
// 平台与底部 −50 dB 测量地板）解出四参数模型
//     fc(v) = fcMin + (fcMax − fcMin) · v^exp
// 残差 RMS：LOW CUT 0.255 dB、HIGH CUT 0.188 dB（逐档 0.18–0.49）。
// 指数两者都落在 ~1.96–2.00，取**精确 2**（平方律），逐档残差不变。
//
// 这一条修正的是最大的两个误差带：照搬显示值的 50 Hz 高通在 20 Hz
// 白扣 16.5 dB（实测参考只扣 ~4 dB），正是 20–40 Hz p95 15.3 dB 的主因；
// 高频端同理，10 kHz vs 真实 12.1 kHz 造成 >2 kHz 的一致偏低。
inline constexpr double kFitCutFcExponent = 2.0;

inline constexpr double kFitLowCutFcMin = 19.0875;
inline constexpr double kFitLowCutFcMax = 760.6250;
inline constexpr double kFitLowCutQ = 0.6868;

inline constexpr double kFitHighCutFcMin = 811.4941;
inline constexpr double kFitHighCutFcMax = 12148.5352;
inline constexpr double kFitHighCutQ = 0.6521;

/// 归一值 → LOW CUT 的**真实**拐点（Hz）。与显示用的 kMeasLowCut* 区分开：
/// 前者驱动 DSP，后者只驱动 UI 文本（要与参考插件的显示串一致）。
inline double lowCutFcFromNorm(double v) noexcept
{
    const double t = std::clamp(v, 0.0, 1.0);
    return kFitLowCutFcMin
         + (kFitLowCutFcMax - kFitLowCutFcMin) * std::pow(t, kFitCutFcExponent);
}

/// 归一值 → HIGH CUT 的**真实**拐点（Hz）。
inline double highCutFcFromNorm(double v) noexcept
{
    const double t = std::clamp(v, 0.0, 1.0);
    return kFitHighCutFcMin
         + (kFitHighCutFcMax - kFitHighCutFcMin) * std::pow(t, kFitCutFcExponent);
}

