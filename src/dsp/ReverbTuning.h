/// DRY/WET 的干增益：min(1, 2(1−q²))，q 为量化到 0.01 栅格的 dw。
/// 与湿增益构成功率互补交叉淡化，两支都被钳在 1，交点 q = 1/√2。
/// 实测 25 个栅格点最大偏差 8e-7。
inline double dryGainFromNorm(double dw) noexcept
{
    const double q = std::floor(dw / kMeasDryWetQuant + 0.5) * kMeasDryWetQuant;
    return std::min(1.0, 2.0 * (1.0 - q * q));
}

/// DRY/WET 的湿增益：min(1, 2q²)。实测最大偏差 2.9e-6。
inline double wetGainFromNorm(double dw) noexcept
{
    const double q = std::floor(dw / kMeasDryWetQuant + 0.5) * kMeasDryWetQuant;
    return std::min(1.0, 2.0 * q * q);
}

/// DECAY 归一值 → 参数显示的秒数（线性 0.5–8.0）。
inline double decaySecFromNorm(double norm) noexcept
{
    return kMeasDecayMinSec + (kMeasDecayMaxSec - kMeasDecayMinSec) * norm;
}

/// DECAY 参数（秒）→ 目标 T60（秒）。
/// **参数值不是 T60**：实测显示 4.25（d=4.25 s）时 T60 = 2.47 s。
/// 幂律距上界形式，在 [0.5, 8.0] 上恒正且单调递增（详见上方推导）。
///
/// 上界之外仍留一道保护：参数被钉在 [0.5, 8.0]，正常不会越界，
/// 但采样率/参数律若将来变动，越界会让底数变负、pow 返回 NaN，
/// 进而污染整个反馈环。这里钳到一个极小的 1/T60（即极长的 T60），
/// 与「反馈趋近 1」的物理趋势一致。
inline double t60FromDecaySec(double decaySec) noexcept
{
    const double slack = kMeasInvT60Bound - decaySec;
    if (slack <= 0.0) return 1.0e4;
    const double inv = kMeasInvT60Scale * std::pow(slack, kMeasInvT60Exponent);
    return inv > 1.0e-4 ? 1.0 / inv : 1.0e4;
}

// ------------------------------------------------------------
// 「目标 T60 → 反馈增益预算」的实现损耗修正
// ------------------------------------------------------------
// 理想 FDN 里每圈只有 g 一处损耗，但本实现的环内还串着两样东西：
//   * damping 一阶低通（kFitDampingHz）；
//   * 被调制延迟线的**分数延迟插值**读取（本身就是个低通）。
// 两者都让实际每圈损耗大于 20·log₁₀(g)，实测 T60 因此一律偏短。
//
// **两种模型的判决（实测，逐线增益已就位后）**：
//   A) 固定每圈损耗 ΔdB ⇒ 1/T60 应出现**恒定的加性**偏移
//      1/T60_实际 = 1/T60_目标 + Δ·sr/(60·L)
//   B) 比例损耗 ⇒ 1/T60_实际 = α · 1/T60_目标
//
// 实测「1/T60 的额外量」随档位：0.154、0.101、0.037、0.0104、
// 0.0068、0.0035、0.0029、0.0024（norm 0.20…0.98）—— 跨 65 倍，
// **不是常数** ⇒ 模型 A 被否证。
// 而 T60_实际/T60_目标 = 0.826、0.801、0.857、0.904、0.910、0.921、
// 0.901、0.853 —— 在 0.80…0.92 之间，基本恒定 ⇒ 模型 B 成立，
// α = 1/比值 ∈ 1.09…1.25（一维扫描在这个区间里定落点）。
//
// 所以修正方式是**把目标 T60 按比例放大**后再编增益预算，
// 而不是加一份固定损耗（后者试过，记录在 tools/fit/fit_t60_scale.py 的
// 文档串里：单一常数只能同时照顾一端，低档位仍差 −18…−22%）。
//
// 历史落点 1.13 由 tools/fit/fit_t60_scale.py 一维扫出（目标 = 各档 T60
// 相对误差绝对值之和，1.0661 → 0.2491），逐档残差：
//     norm     0.20  0.50  0.70  0.86  0.90  0.94  0.96  0.98
//     相对%   −5.2  −7.3  −6.3  −1.5  −0.2  +0.8  +1.9  +1.7
//
// **现在的落点 1.01 与 kFitDampingHz 一起由 tools/fit/fit_damping_t60.py
// 联立扫出。** 为什么必须联立：本常数补的就是环内那两处损耗，而其中
// 「插值」那一项在 ModulatedDelay 换成 3 阶 Lagrange 后掉了 5.6 倍
//（8 kHz 每圈均值 −0.80 → −0.14 dB，见 ReverbCore.hpp 的推导）。
// 损耗少了，原来的 1.13 就变成**补过头**，全带 T60 一律偏长。
// 分开扫会来回打架：先修 damping 则全带偏长，再修 scale 又把高频压回去。
//
// 落点从 1.13 掉到 1.01 本身就是这条链的自证：环内损耗被插值改动消掉
// 一大半后，只剩约 1% 需要补。
//
// 逐带 T60 残差（decay=0.5，**含 §7.7 的 trim 之后**的当前值）：
// 125 Hz −3.4%、250 −9.4%、500 +3.5%、1 k +9.5%、2 k −6.1%、4 k −8.5%、
// 8 k −9.3% ⇒ **最差 9.5%**。（§7.6 刚落地时是 9.4%，trim 只动电平不动
// 衰减率，两者的 0.1 个百分点差是测量噪声。）
// 关键是**符号正负交替**（修前是高频单调亏空、越晚越亏），说明系统性的
// 衰减率偏差已消除，剩下的是各带模式分布的随机残差 —— 那要靠改线长/路数，
// 与 §10.2 的低频错位项同源，不是这两个常数能再压的。
//
// **已知代价：上端 DECAY 档的 T60 因此退化**（实测，docs/REFERENCE.md §12.6）。
// norm 0.90/0.94/0.96/0.98 从 1.13 年代的 −0.2/+0.8/+1.9/+1.7% 变成
// **−10.5/−8.5/−7.8/−6.5%**（一律偏短）。成因是 fit_damping_t60.py 的目标只含
// decay=0.5 的逐带 T60，**没有上端档位**，所以解不知道自己在牺牲它们。
//
// 但 1.01 仍是正确落点，已核算「逐带 + 上端」的联合最差：
//     scale   逐带最差   上端最差   取最差
//     1.01      9.5%     10.5%    10.5%   ← 最优，且平坦
//     1.03     11.7%      8.7%    11.7%
//     1.13     22.6%      4.7%    22.6%
// 旧的 1.13 上端漂亮是因为它在补偿插值损耗；插值修好后那份补偿变成补过头，
// 而过头量在低 decay 档（每秒圈数多）更明显，所以逐带口径先炸。
// 要同时压下两边，本常数必须**随档位变化**（分段或逐线标定）—— 新的自由度，
// 与 §7.4 结尾「单常数照顾不了两端」同源，只是那里说的是低档位。
// **该自由度已落地**，见下面的 kFitT60ScaleKnotVal（§12.7）。注意上面这张
// 「逐带/上端」联合表里的上端列是**全带口径**，§12.7 已证明它在这里会骗人；
// 表本身作为历史记录保留，但不要再据它下新结论。
//
// 注意本常数**修不了** DECAY=1.0 那一档（那是拓扑天花板，见 §12.4）。
// §12.4 里 439 s 的饱和值是**线性插值年代**测的，换 Lagrange 后天花板已上移
//（norm=1.0 的 45 s 净跌 15.69 → 13.94 dB，参考 10.82），但饱和点本身
// **未重测** ⇒ 不要再引用 439 s / 16% 这两个数字。
inline constexpr double kFitT60BudgetScale = 0.990000;

// ------------------------------------------------------------
// 逐档修正表：kFitT60BudgetScale 随 DECAY 档变化
// ------------------------------------------------------------
// 实际用的预算倍数 = kFitT60BudgetScale · t60BudgetScaleFromNorm(norm)。
// 表全为 1.0 时与单常数年代**逐位等价**，所以这张表是纯增量的。
//
// **为什么需要逐档**：上面那段「已知代价」是对的，但它引用的上端数字
//（−6.5…−10.5%，一律偏短）是**全带口径**测的，而全带口径在这里会骗人。
// 用尾长稳定的逐带口径（tools/fit/t60_band_guard.py）重测，同一个
// scale=1.01 的 build：
//
//     decay   逐带相对误差范围        最差    整体缩放最优倍数
//     0.20    −11.0 … +35.2 %       35.2%   0.892
//     0.50     −9.4 …  +9.4 %        9.4%   1.000
//     0.70     −8.4 …  −6.2 % (n=5)   8.4%   1.078
//     0.86    −13.2 …  +5.5 %       13.2%   1.040
//     0.94     −9.2 … +18.5 %       18.5%   0.956
//
// 两处与全带口径**矛盾**，且矛盾方向相反：
//   * 全带说每一档都要把 scale 往上推（1.068…1.204）；
//   * 逐带说 0.20 与 0.94 要往**下**（0.892 / 0.956）。
// 0.94 档全带读出「一律偏短」，而 4 k/8 k 实际**偏长 +16…+18%** ——
// 全带把一次符号反转平均成了单向亏空。照全带的结论建律，会把这两档推反。
// 成因见 tools/fit/diag_t60_caliber.py：全带是各带指数之和，候选的逐带
// 离散度比参考大（25.2× vs 20.0×），单直线拟合必然比任何单带都陡。
//
// **形式：在 norm 上分段线性，节点就是上面 5 个实测档。**
// 不用幂律/多项式：实测落点是**非单调的拱形**（0.90 → 1.01 → 1.09 → 1.05
// → 0.97），任何低阶解析式都要么拟不出拱形、要么在节点之间乱摆。分段线性
// 在节点上精确复现实测，节点之间是最保守的插值，且天然不会外推出野值。
//
// 每个节点的值由 tools/fit/fit_t60_scale_law.py 逐档扫出（真编译、真渲染、
// 真测量；目标 = 该档逐带相对误差的**最差值**，与验收口径同形）。
inline constexpr int kFitT60ScaleKnotCount = 5;

/// 节点档位（DECAY 归一值），必须**升序**。
inline constexpr double kFitT60ScaleKnotNorm[kFitT60ScaleKnotCount] = {
    0.20, 0.50, 0.70, 0.86, 0.94
};

/// 各节点的预算倍数修正（1.0 = 不修正）。
///
/// 落点由 tools/fit/fit_t60_broadband.py 逐档扫出（2026-08-05，在 15 阶插值 +
/// fc=20000 的环路上，每次试探真编译→真渲染→真测量）。目标是**1 kHz 锚点带的
/// 相对误差**，即纯宽带项，**不是**逐带最差 —— 理由见下面「代价」一段。
///
///     decay    落点       1kHz 前 → 后      逐带最差(前→后)   逐带范围(后)
///     0.20   1.082200    −8.66% → +1.19%     9.9 → 17.5     −2.9 … +17.5
///     0.50   1.173400   −13.24% → −1.13%    22.3 → 17.1    −11.1 … +17.1
///     0.70   1.242500   −18.49% → +0.33%    19.7 → 23.7     −2.0 … +23.7
///     0.86   1.135100   −12.73% → −1.38%    26.7 → 36.1     −8.8 … +36.1
///     0.94   1.033200    −3.53% → −0.32%    50.5 → 52.8     −8.6 … +52.8
///
/// 五档宽带项全部压进 **±1.4%**（原 −3.5…−18.5%）。落点沿 decay 呈**拱形**
///（1.082 → 1.173 → 1.243 → 1.135 → 1.033，0.70 最深），正是分段线性能表达
/// 而单个标量表达不了的形状 —— 这就是本表存在的理由（§12.6 结尾的预言成立）。
///
/// ### 代价：逐带最差在四档里**变差**。为什么这仍然是对的落点。
///
/// 缩放**同倍**移动该档所有带，只能平移、不能收缩带间跨度。所以当某档的逐带
/// 残差**跨零**时，把 1 kHz 抬平就必然把原本已偏正的带推得更正。0.94 档最极端：
/// 1 kHz 只差 −0.3%，而 8 kHz **+52.8%**（ref 5.533 s vs cand 8.455 s）——
/// 那 52.8% 与宽带项无关，是带间散布，本常数取任何值都碰不到它。
///
/// 用「逐带最差」当目标，会让这条压不动的带主导整个扫描，把真正该压的宽带项
/// 挤掉 —— 即 §10.2.2 tilt shelf 的老坑（拿一个标量去追一片逐带散布）。
/// 上一代 tools/fit/fit_t60_scale_law.py 正是这个目标，其落点已作废；
/// 它的搜索网格 [0.50…1.06] 也框不住本轮的最优点（四档在 1.06 之上）。
///
/// 验收侧确认这是净收益（band_report.py 全 6 档，落地后实测）：
///     2k–20k  2.36 → **2.11 dB ✓**      全档全带 max  13.61 → **13.50 dB**
/// 无任何频带退化。逐带最差的上升**没有**兑换成平滑谱退化，因为它集中在长尾档
/// 的高频带，那里的绝对能量已经很低。
///
/// ### 与 kFitDampingHz 的正交性是**近似**的，不是精确的
///
/// §12.9.3 讲锚定让 fc（形状）与本表（宽带）正交。实测**方向对但不严格**：
/// 本表落地后重测 decay=0.50 的锚定缺口 D，最差|D| 3.40 → 3.41 dB/s（几乎不动
/// ⇒ 结论成立），但单带最多移动 +1.12（125 Hz 从 +2.20 到 +3.32）。
/// 成因：改 budget 改的是 g_i，每圈损耗形状不变，但逐带 T60 的回归窗随衰减
/// 总量移动，二阶耦合由此进来。
/// ⇒ 将来若重扫 fc，应在本表落地**之后**做，不要指望两者完全解耦。
inline constexpr double kFitT60ScaleKnotVal[kFitT60ScaleKnotCount] = {
    1.082200, 1.173400, 1.242500, 1.135100, 1.033200
};

/// DECAY 归一值 → 预算倍数修正（节点间线性，两端取端点值不外推）。
///
/// 端点外**故意不外推**：norm < 0.20 与 > 0.94 都没有可信的逐带实测
///（低档尾巴太短、0.94 以上是拓扑天花板区，见 §12.4），线性外推会把
/// 拱形的下降段一路拉到 norm=1.0，在最敏感的极限档上放大误差。
inline double t60BudgetScaleFromNorm(double norm) noexcept
{
    if (norm <= kFitT60ScaleKnotNorm[0]) return kFitT60ScaleKnotVal[0];
    for (int i = 1; i < kFitT60ScaleKnotCount; ++i)
    {
        if (norm <= kFitT60ScaleKnotNorm[i])
        {
            const double n0 = kFitT60ScaleKnotNorm[i - 1];
            const double n1 = kFitT60ScaleKnotNorm[i];
            const double t = (norm - n0) / (n1 - n0);
            return kFitT60ScaleKnotVal[i - 1]
                 + t * (kFitT60ScaleKnotVal[i] - kFitT60ScaleKnotVal[i - 1]);
        }
    }
    return kFitT60ScaleKnotVal[kFitT60ScaleKnotCount - 1];
}

// 注：反馈增益的换算已移到 WetCore::setDecay（ReverbCore.hpp），因为它必须
// **逐线**进行：g_i = 10^(−3·L_i/(T60·kFitT60BudgetScale·sr))。
// （早先这行写的是「+ kFitDampLossDb」的加性形式，那是上面已被否证的模型 A，
//   常数本身也已删除；留着会误导人以为两种修正并存。）
// 这里曾有一个按**平均**线长算单一 g 的 feedbackFromT60()，是错的 ——
// 8 条线长差 2.4 倍，共用 g 时每秒衰减率也差 2.4 倍，尾巴成了多指数混合，
// 实测 T60 比目标短 10–22% 且随 decay 单调恶化。同理 meanDelay() 也已删除：
// 平均线长在这个模型里没有物理意义，留着只会诱使人再写出按均值算的增益。

/// 归一值 → PRE-DELAY 毫秒数（幂律，指数 5/3）。
/// 只在参数变化时调用（非音频热路径），直接用 std::cbrt 即可。
inline double predelayMsFromNorm(double norm) noexcept
{
    if (norm <= 0.0) return kMeasPredelayMinMs;
    if (norm >= 1.0) return kMeasPredelayMaxMs;
    // norm^(5/3) = norm · cbrt(norm²)
    const double shaped = norm * std::cbrt(norm * norm);
    return kMeasPredelayMinMs + (kMeasPredelayMaxMs - kMeasPredelayMinMs) * shaped;
}

/// PRE-DELAY 毫秒数 → 归一值（UI/对拍脚本用）。
inline double predelayNormFromMs(double ms) noexcept
{
    const double t = (ms - kMeasPredelayMinMs) / (kMeasPredelayMaxMs - kMeasPredelayMinMs);
    if (t <= 0.0) return 0.0;
    if (t >= 1.0) return 1.0;
    return std::pow(t, 1.0 / kMeasPredelayExponent);
}

