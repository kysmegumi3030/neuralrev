// ------------------------------------------------------------
// 「DECAY 参数（秒）→ T60」律：幂律距上界形式
// ------------------------------------------------------------
//     1/T60 = kMeasInvT60Scale · (kMeasInvT60Bound − decaySec)^kMeasInvT60Exponent
//
// 为什么不是线性（前一版的错解，工具 tools/fit/fit_decay_law.py）：
// 旧模型 `1/T60 = −0.117657·d + 0.907644` 在 d = 7.7145 s（norm 0.9619）
// **穿过零点**，之后靠 `1e3` 钳位兜着。而实测 1/T60 在上端仍为正且可测
// （d=7.85 s 时 T60 = 72.7 s），零点位置根本不存在 ⇒ 上端全是无效外推：
// 旧模型在 d=7.70 s 给出 593 s，实测 37.7 s，**偏长 1474%**。
//
// 幂律距上界形式的物理含义：kMeasInvT60Bound 是「反馈增益恰好到 1」的
// 虚拟参数值。落点 **8.030 s > 参数上限 8.0 s** —— 也就是说参考在
// norm=1.0 时反馈**还没到** 1（所以不发散），但已非常接近（T60 ≥ 526 s，
// 听感上就是无限延音）。这条形式在整个定义域内恒正且单调递减，
// 无需任何钳位。
//
// 测法（关键，否则测出来的是窗长而不是混响）：
//   * 主口径用 **RMS 包络回归**，不用 EDC。EDC 的反向累积能量在窗末
//     必然归零，尾巴超过窗长的档位会出现人造膝点，T60 被系统性低估
//     —— 同一 norm=1.0 档，20 s 窗给 47.8 s、25 s 窗给 60.2 s，
//     结果随窗长漂移即为该偏置的指纹；
//   * 窗长 45 s，包络窗自适应取 T60/40；
//   * 回归段跨度不足 25 dB 的档位（只有 norm=1.0）不进残差 —— 它的斜率
//     只反映窗内那一小段，硬拟合会把整条曲线拽偏。
//
// **但它也不能被完全丢掉**：「T60 ≥ 526 s」是单边硬信息，丢掉等于放开
// 模型在定义域末端自由外推。第一版就是这么丢的，解跑到 D=8.075，在
// d=8.0 处只给 258 s —— 违反实测下界 2 倍，DECAY=1.0 档实际衰减快了约
// 2 倍（由 tools/measure/ref_decay_extreme.py 的对拍抓出）。
// 现在它以**约束**形式参与：fit_power_to_bound() 在 D 网格里排除所有
// 违反下界的解，四种候选形式统一用 bounds_ok() 检查（否则「谁残差小」
// 的比较不公平 —— 不受约束的形式能靠末端乱跑换残差）。
//
// 拟合口径 = log(1/T60) 的残差（1/T60 全程跨 500 倍，用线性残差会让
// 低 decay 档独占权重）。残差 RMS 0.0431 ⇒ **T60 相对误差 4.4%**。
// 比无约束解的 3.1% 差一点，是**故意付的代价**：用中段约 1% 的精度
// 换掉上端 2 倍的错。现在 d=8.0 处给 592 s，满足 ≥526 s 的下界。
inline constexpr double kMeasInvT60Bound = 8.030000;
inline constexpr double kMeasInvT60Scale = 0.09205155;
inline constexpr double kMeasInvT60Exponent = 1.140206;

